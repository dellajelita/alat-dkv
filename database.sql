-- ============================================================================
-- AlatDKV - Skema Basis Data, RLS, dan Data Contoh
-- ============================================================================

-- 1. Tabel alat
CREATE TABLE IF NOT EXISTS public.alat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama text NOT NULL UNIQUE,
  kategori text NOT NULL,
  stok integer NOT NULL DEFAULT 0,
  keterangan text NOT NULL DEFAULT '',
  aktif boolean NOT NULL DEFAULT true,
  CONSTRAINT alat_nama_panjang_chk CHECK (char_length(btrim(nama)) BETWEEN 3 AND 40),
  CONSTRAINT alat_kategori_chk CHECK (
    kategori IN ('kamera', 'pencahayaan', 'audio', 'tablet', 'aksesori')
  ),
  CONSTRAINT alat_stok_chk CHECK (stok BETWEEN 0 AND 50)
);

-- 2. Tabel peminjaman_alat
CREATE TABLE IF NOT EXISTS public.peminjaman_alat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alat_id bigint NOT NULL REFERENCES public.alat(id) ON DELETE RESTRICT,
  peminjam text NOT NULL,
  kelas text NOT NULL,
  keperluan text NOT NULL,
  jumlah integer NOT NULL,
  tgl_pinjam date NOT NULL,
  tgl_kembali date NOT NULL,
  status text NOT NULL DEFAULT 'menunggu',
  alasan_tolak text NULL,
  kondisi_kembali text NULL,
  tgl_dikembalikan date NULL,
  dibuat timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT peminjaman_peminjam_panjang_chk CHECK (char_length(btrim(peminjam)) BETWEEN 3 AND 40),
  CONSTRAINT peminjaman_kelas_panjang_chk CHECK (char_length(btrim(kelas)) BETWEEN 3 AND 20),
  CONSTRAINT peminjaman_keperluan_panjang_chk CHECK (char_length(btrim(keperluan)) BETWEEN 5 AND 120),
  CONSTRAINT peminjaman_jumlah_chk CHECK (jumlah BETWEEN 1 AND 5),
  CONSTRAINT peminjaman_rentang_tanggal_chk CHECK (tgl_kembali >= tgl_pinjam),
  CONSTRAINT peminjaman_status_chk CHECK (
    status IN ('menunggu', 'dipinjam', 'dikembalikan', 'ditolak')
  ),
  CONSTRAINT peminjaman_kondisi_kembali_chk CHECK (
    kondisi_kembali IS NULL
    OR kondisi_kembali IN ('baik', 'rusak ringan', 'rusak berat')
  )
);

CREATE INDEX IF NOT EXISTS idx_peminjaman_alat_id ON public.peminjaman_alat(alat_id);
CREATE INDEX IF NOT EXISTS idx_peminjaman_status ON public.peminjaman_alat(status);

-- 3. Row Level Security (RLS)
-- Kunci publik (anon) hanya boleh membaca tabel alat; peminjaman_alat tidak boleh diakses publik.
ALTER TABLE public.alat ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.peminjaman_alat ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "alat_select_public" ON public.alat;
CREATE POLICY "alat_select_public"
  ON public.alat
  FOR SELECT
  TO anon, authenticated
  USING (true);

REVOKE ALL ON TABLE public.peminjaman_alat FROM anon, authenticated;
REVOKE ALL ON TABLE public.alat FROM anon, authenticated;
GRANT SELECT ON TABLE public.alat TO anon, authenticated;

